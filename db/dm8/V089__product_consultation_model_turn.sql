CREATE TABLE con3_model_turn (
    turn_id VARCHAR(36) PRIMARY KEY,
    task_id VARCHAR(36) NOT NULL,
    task_version BIGINT NOT NULL,
    actor_subject VARCHAR(200) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    request_sha VARCHAR(64) NOT NULL,
    result_set_id VARCHAR(36),
    result_sha VARCHAR(64),
    model_id VARCHAR(200) NOT NULL,
    prompt_version VARCHAR(100) NOT NULL,
    request_json CLOB NOT NULL,
    raw_output CLOB NOT NULL,
    output_json CLOB NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    retention_ref VARCHAR(500) NOT NULL,
    retention_version BIGINT NOT NULL,
    retention_evidence_sha VARCHAR(64) NOT NULL,
    CONSTRAINT fk_con3_model_task FOREIGN KEY (task_id) REFERENCES con3_task(task_id),
    CONSTRAINT uq_con3_model_request UNIQUE (task_id, actor_subject, request_id),
    CONSTRAINT ck_con3_model_kind CHECK (kind IN ('PROPOSAL','EXPLANATION')),
    CONSTRAINT ck_con3_model_version CHECK (task_version > 0 AND retention_version > 0),
    CONSTRAINT ck_con3_model_expiry CHECK (expires_at > created_at)
);
