CREATE TABLE idp_workspace_register_request (
    request_id VARCHAR(36) PRIMARY KEY,
    receipt_id VARCHAR(36) NOT NULL,
    workspace_id VARCHAR(36) NOT NULL,
    operation VARCHAR(16) NOT NULL,
    subject_id VARCHAR(200) NOT NULL,
    operator_organization VARCHAR(36) NOT NULL,
    maintainer_version BIGINT NOT NULL,
    certificate_sha CHAR(64) NOT NULL,
    key_sha CHAR(64) NOT NULL,
    request_sha CHAR(64) NOT NULL,
    workspace_sha CHAR(64) NOT NULL,
    result_sha CHAR(64) NOT NULL,
    prepared_at TIMESTAMP NOT NULL,
    receipt_until TIMESTAMP NOT NULL,
    organization VARCHAR(36) NOT NULL,
    scope_version BIGINT NOT NULL,
    workspace_state VARCHAR(16) NOT NULL,
    policy_ref VARCHAR(200) NOT NULL,
    policy_sha CHAR(64) NOT NULL,
    registry_sha CHAR(64) NOT NULL,
    valid_until TIMESTAMP NOT NULL,
    primary_database_sha CHAR(64) NOT NULL,
    authority_database_sha CHAR(64) NOT NULL,
    approval_ref VARCHAR(500) NOT NULL,
    approval_sha CHAR(64) NOT NULL,
    approved_receipt_until TIMESTAMP NOT NULL,
    intent_until TIMESTAMP NOT NULL,
    prepared_sha CHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL,
    CONSTRAINT uq_idp_wr_workspace UNIQUE(workspace_id),
    CONSTRAINT uq_idp_wr_receipt UNIQUE(receipt_id),
    CONSTRAINT uq_idp_wr_key UNIQUE(workspace_id,subject_id,certificate_sha,operation,key_sha),
    CONSTRAINT fk_idp_wr_workspace FOREIGN KEY(workspace_id) REFERENCES idp_workspace(workspace_id),
    CONSTRAINT ck_idp_wr CHECK(operation='REGISTER' AND scope_version>0 AND maintainer_version>0
        AND workspace_state='ACTIVE' AND state IN ('PENDING','READY') AND request_id<>receipt_id
        AND organization=operator_organization AND primary_database_sha<>authority_database_sha
        AND prepared_at<intent_until AND intent_until<=receipt_until
        AND receipt_until<=valid_until AND receipt_until<=approved_receipt_until)
);
